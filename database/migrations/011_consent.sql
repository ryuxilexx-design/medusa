-- Patient consent (Law of the Republic of Uzbekistan «On personal data», ZRU-547; health data is a special category):
-- consent to the processing of personal and health data, and — separately, optional — consent to Telegram
-- reminders/notices. The rows are evidence (who, when, how, which text version), so they are append-only:
-- a withdrawal or a refusal is a NEW row with granted = false; the latest row of a kind is the current state.
-- The consent text itself is versioned in packages/contracts (CONSENT_TEXTS) and must be reviewed by a lawyer.

CREATE TABLE patient_consents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES tenants(id),
  patient_id uuid NOT NULL,
  kind text NOT NULL CHECK (kind IN ('data_processing', 'notifications')),
  granted boolean NOT NULL,
  text_version text NOT NULL CHECK (length(text_version) BETWEEN 1 AND 40),
  method text NOT NULL CHECK (method IN ('signed_paper', 'telegram', 'verbal')),
  -- staff member who recorded it (membership) and their name at that moment; both NULL when the Telegram bot recorded it
  recorded_by uuid,
  recorded_by_name text,
  recorded_at timestamptz NOT NULL DEFAULT demo_now(),
  note text CHECK (note IS NULL OR length(note) <= 500),
  -- insertion order: breaks ties between rows written at the same instant (latest = highest seq)
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  CHECK ((recorded_by IS NULL) = (recorded_by_name IS NULL)),
  CHECK (method = 'telegram' OR recorded_by_name IS NOT NULL),
  FOREIGN KEY (tenant_id, patient_id) REFERENCES patients(tenant_id, id),
  FOREIGN KEY (tenant_id, recorded_by) REFERENCES memberships(tenant_id, id)
);
CREATE INDEX patient_consents_patient ON patient_consents (patient_id, kind, recorded_at DESC, seq DESC);

CREATE FUNCTION forbid_consent_change() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'patient consents are append-only' USING ERRCODE = 'P0001';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER patient_consents_append_only BEFORE UPDATE OR DELETE ON patient_consents
  FOR EACH ROW EXECUTE FUNCTION forbid_consent_change();
